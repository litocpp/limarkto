#!/usr/bin/env python3
"""Generate the CommonMark entity table from the WHATWG HTML JSON snapshot."""
import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.request import urlopen


SOURCE = "https://html.spec.whatwg.org/entities.json"
SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"
OUTPUT = Path(__file__).resolve().parents[1] / "src/entities.inc"


def generate(source):
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise ValueError("WHATWG entities.json checksum mismatch")
    entities = json.loads(source)
    rows = []
    for name, entry in sorted(entities.items(), key=lambda item: item[0].removesuffix(";")):
        if not name.endswith(";"):
            continue
        if not re.fullmatch(r"&[A-Za-z][A-Za-z0-9]*;", name) or len(name) > 33:
            raise ValueError(f"Unsupported entity name: {name}")
        characters = entry["characters"]
        if [ord(char) for char in characters] != entry["codepoints"]:
            raise ValueError(f"Inconsistent entity codepoints: {name}")
        encoded = characters.encode("utf-8")
        if not encoded or len(encoded) >= 8 or 0 in encoded:
            raise ValueError(f"Unsupported entity bytes: {name}")
        values = ", ".join(str(byte) for byte in (*encoded, 0))
        rows.append(f'{{"{name[1:-1]}", {{{values}}}}},')
    if len(rows) != 2125:
        raise ValueError("Unexpected WHATWG entity count")
    return "\n".join([
        "// Generated by tools/generate_entities.py; see LICENSE-WHATWG.",
        f"// Source: {SOURCE} (SHA-256: {SHA256})",
        "// clang-format off", *rows, "// clang-format on", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, help="Use a local entities.json snapshot")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true", help="Check without rewriting the table")
    args = parser.parse_args()
    if args.input:
        source = args.input.read_bytes()
    else:
        with urlopen(SOURCE, timeout=30) as response:
            source = response.read()
    generated = generate(source).encode("ascii")
    if args.check:
        if args.output.read_bytes() != generated:
            parser.error("Entity table differs from the pinned WHATWG snapshot")
        print("checked 2125 WHATWG named entities")
    else:
        args.output.write_bytes(generated)
        print("generated 2125 WHATWG named entities")


if __name__ == "__main__":
    main()
